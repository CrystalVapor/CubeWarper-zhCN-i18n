def main():
    remaining=json.loads((ROOT/'remaining_main.json').read_text(encoding='utf-8'))
    result={}
    for ns,block in TEXT.items():
        values=block.splitlines()
        # Store actual newlines in tooltip text; use escaped lines in source.
        values=[v.replace('\\n','\n') for v in values]
        keys=list(remaining[ns])
        if len(values)!=len(keys):raise ValueError((ns,len(values),len(keys)))
        result[ns]=dict(zip(keys,values))
        # Verify Java format placeholders including their order.
        import re
        for k,v in result[ns].items():
            before=re.findall(r'%(?:\d+\$)?[sdif]',remaining[ns][k])
            after=re.findall(r'%(?:\d+\$)?[sdif]',v)
            if before!=after:raise ValueError((k,before,after))
    (ROOT/'manual_mod_translations_quest_ui.json').write_text(json.dumps(result,ensure_ascii=False,indent=2),encoding='utf-8')
    print({ns:len(v) for ns,v in result.items()})

if __name__=='__main__':main()
